/* ============================================================================
   02 - Tabloları oluşturur (fiziksel tasarım)
   35 tablo = 25 lookup + 7 ana tablo + 3 ML tablosu
   Sıra önemlidir: önce referans verilen (lookup) tablolar, sonra ana tablolar.
   ============================================================================ */
USE GelirAnalizDB;
GO

/* ---------------------------------------------------------------------------
   A) LOOKUP (REFERANS) TABLOLARI - 25 adet
   Her kategorik metin değeri yalnızca bir kez saklanır.
   ID'ler küçük olduğu için TINYINT (0-255) yeterlidir.
   --------------------------------------------------------------------------- */

-- Demografik lookup'lar (PERSON tarafından kullanılır)
CREATE TABLE SEX (
    SexID            TINYINT      NOT NULL CONSTRAINT PK_SEX PRIMARY KEY,
    SexName          NVARCHAR(10) NOT NULL CONSTRAINT UQ_SEX_Name UNIQUE
);

CREATE TABLE RACE (
    RaceID           TINYINT      NOT NULL CONSTRAINT PK_RACE PRIMARY KEY,
    RaceName         NVARCHAR(40) NOT NULL CONSTRAINT UQ_RACE_Name UNIQUE
);

CREATE TABLE HISPANIC_ORIGIN (
    HispanicOriginID TINYINT      NOT NULL CONSTRAINT PK_HISPANIC_ORIGIN PRIMARY KEY,
    OriginName       NVARCHAR(40) NOT NULL CONSTRAINT UQ_HISPANIC_ORIGIN_Name UNIQUE
);

CREATE TABLE MARITAL_STATUS (
    MaritalStatusID  TINYINT      NOT NULL CONSTRAINT PK_MARITAL_STATUS PRIMARY KEY,
    StatusName       NVARCHAR(40) NOT NULL CONSTRAINT UQ_MARITAL_STATUS_Name UNIQUE
);

CREATE TABLE EDUCATION (
    EducationID      TINYINT      NOT NULL CONSTRAINT PK_EDUCATION PRIMARY KEY,
    EducationName    NVARCHAR(60) NOT NULL CONSTRAINT UQ_EDUCATION_Name UNIQUE,
    EducationLevel   TINYINT      NOT NULL CONSTRAINT CK_EDUCATION_Level CHECK (EducationLevel BETWEEN 0 AND 16)
                     CONSTRAINT UQ_EDUCATION_Level UNIQUE
);

CREATE TABLE EDU_ENROLLMENT (
    EduEnrollmentID  TINYINT      NOT NULL CONSTRAINT PK_EDU_ENROLLMENT PRIMARY KEY,
    EnrollmentName   NVARCHAR(40) NOT NULL CONSTRAINT UQ_EDU_ENROLLMENT_Name UNIQUE
);

CREATE TABLE CITIZENSHIP (
    CitizenshipID    TINYINT      NOT NULL CONSTRAINT PK_CITIZENSHIP PRIMARY KEY,
    CitizenshipName  NVARCHAR(60) NOT NULL CONSTRAINT UQ_CITIZENSHIP_Name UNIQUE
);

CREATE TABLE COUNTRY (
    CountryID        TINYINT      NOT NULL CONSTRAINT PK_COUNTRY PRIMARY KEY,
    CountryName      NVARCHAR(50) NOT NULL CONSTRAINT UQ_COUNTRY_Name UNIQUE
);

-- Evet / Hayır / "Not in universe" tipindeki 4 sütunun paylaştığı cevap tablosu
CREATE TABLE ANSWER (
    AnswerID         TINYINT      NOT NULL CONSTRAINT PK_ANSWER PRIMARY KEY,
    AnswerText       NVARCHAR(40) NOT NULL CONSTRAINT UQ_ANSWER_Text UNIQUE
);

-- İş / finans lookup'ları
CREATE TABLE CLASS_OF_WORKER (
    ClassOfWorkerID  TINYINT      NOT NULL CONSTRAINT PK_CLASS_OF_WORKER PRIMARY KEY,
    ClassName        NVARCHAR(40) NOT NULL CONSTRAINT UQ_CLASS_OF_WORKER_Name UNIQUE
);

CREATE TABLE MAJOR_INDUSTRY (
    MajorIndustryID  TINYINT      NOT NULL CONSTRAINT PK_MAJOR_INDUSTRY PRIMARY KEY,
    IndustryName     NVARCHAR(60) NOT NULL CONSTRAINT UQ_MAJOR_INDUSTRY_Name UNIQUE
);

-- Detay sektör kodu kaynak veride zaten sayısal ve sabittir: doğal anahtar olarak kullanılır
CREATE TABLE INDUSTRY (
    IndustryCode     TINYINT      NOT NULL CONSTRAINT PK_INDUSTRY PRIMARY KEY,
    MajorIndustryID  TINYINT      NOT NULL
                     CONSTRAINT FK_INDUSTRY_MAJOR REFERENCES MAJOR_INDUSTRY (MajorIndustryID)
);

CREATE TABLE MAJOR_OCCUPATION (
    MajorOccupationID TINYINT      NOT NULL CONSTRAINT PK_MAJOR_OCCUPATION PRIMARY KEY,
    OccupationName    NVARCHAR(60) NOT NULL CONSTRAINT UQ_MAJOR_OCCUPATION_Name UNIQUE
);

CREATE TABLE OCCUPATION (
    OccupationCode    TINYINT      NOT NULL CONSTRAINT PK_OCCUPATION PRIMARY KEY,
    MajorOccupationID TINYINT      NOT NULL
                      CONSTRAINT FK_OCCUPATION_MAJOR REFERENCES MAJOR_OCCUPATION (MajorOccupationID)
);

CREATE TABLE EMPLOYMENT_STATUS (
    EmploymentStatusID TINYINT      NOT NULL CONSTRAINT PK_EMPLOYMENT_STATUS PRIMARY KEY,
    StatusName         NVARCHAR(50) NOT NULL CONSTRAINT UQ_EMPLOYMENT_STATUS_Name UNIQUE
);

CREATE TABLE UNEMPLOYMENT_REASON (
    UnemploymentReasonID TINYINT      NOT NULL CONSTRAINT PK_UNEMPLOYMENT_REASON PRIMARY KEY,
    ReasonName           NVARCHAR(40) NOT NULL CONSTRAINT UQ_UNEMPLOYMENT_REASON_Name UNIQUE
);

CREATE TABLE TAX_FILER_STATUS (
    TaxFilerStatusID TINYINT      NOT NULL CONSTRAINT PK_TAX_FILER_STATUS PRIMARY KEY,
    StatusName       NVARCHAR(40) NOT NULL CONSTRAINT UQ_TAX_FILER_STATUS_Name UNIQUE
);

-- Hane / ikamet / göç lookup'ları
CREATE TABLE HOUSEHOLD_DETAIL (
    HouseholdDetailID TINYINT      NOT NULL CONSTRAINT PK_HOUSEHOLD_DETAIL PRIMARY KEY,
    DetailName        NVARCHAR(60) NOT NULL CONSTRAINT UQ_HOUSEHOLD_DETAIL_Name UNIQUE
);

CREATE TABLE HOUSEHOLD_SUMMARY (
    HouseholdSummaryID TINYINT      NOT NULL CONSTRAINT PK_HOUSEHOLD_SUMMARY PRIMARY KEY,
    SummaryName        NVARCHAR(60) NOT NULL CONSTRAINT UQ_HOUSEHOLD_SUMMARY_Name UNIQUE
);

CREATE TABLE FAMILY_UNDER_18 (
    FamilyUnder18ID  TINYINT      NOT NULL CONSTRAINT PK_FAMILY_UNDER_18 PRIMARY KEY,
    ParentsPresent   NVARCHAR(40) NOT NULL CONSTRAINT UQ_FAMILY_UNDER_18_Name UNIQUE
);

CREATE TABLE REGION (
    RegionID         TINYINT      NOT NULL CONSTRAINT PK_REGION PRIMARY KEY,
    RegionName       NVARCHAR(30) NOT NULL CONSTRAINT UQ_REGION_Name UNIQUE
);

CREATE TABLE STATE (
    StateID          TINYINT      NOT NULL CONSTRAINT PK_STATE PRIMARY KEY,
    StateName        NVARCHAR(40) NOT NULL CONSTRAINT UQ_STATE_Name UNIQUE
);

CREATE TABLE MSA_CHANGE (
    MsaChangeID      TINYINT      NOT NULL CONSTRAINT PK_MSA_CHANGE PRIMARY KEY,
    ChangeName       NVARCHAR(40) NOT NULL CONSTRAINT UQ_MSA_CHANGE_Name UNIQUE
);

CREATE TABLE REGION_CHANGE (
    RegionChangeID   TINYINT      NOT NULL CONSTRAINT PK_REGION_CHANGE PRIMARY KEY,
    ChangeName       NVARCHAR(40) NOT NULL CONSTRAINT UQ_REGION_CHANGE_Name UNIQUE
);

CREATE TABLE WITHIN_REGION_MOVE (
    WithinRegionMoveID TINYINT      NOT NULL CONSTRAINT PK_WITHIN_REGION_MOVE PRIMARY KEY,
    MoveName           NVARCHAR(40) NOT NULL CONSTRAINT UQ_WITHIN_REGION_MOVE_Name UNIQUE
);
GO

/* ---------------------------------------------------------------------------
   B) ANA TABLOLAR - 7 adet
   PERSON merkezdedir. 1:1 tablolarda PersonID hem PK hem FK'dır.
   --------------------------------------------------------------------------- */

CREATE TABLE PERSON (
    PersonID                 INT     NOT NULL IDENTITY(1,1) CONSTRAINT PK_PERSON PRIMARY KEY,
    Age                      TINYINT NOT NULL CONSTRAINT CK_PERSON_Age CHECK (Age BETWEEN 0 AND 120),
    SexID                    TINYINT NOT NULL CONSTRAINT FK_PERSON_SEX       REFERENCES SEX (SexID),
    RaceID                   TINYINT NOT NULL CONSTRAINT FK_PERSON_RACE      REFERENCES RACE (RaceID),
    HispanicOriginID         TINYINT NOT NULL CONSTRAINT FK_PERSON_HISPANIC  REFERENCES HISPANIC_ORIGIN (HispanicOriginID),
    MaritalStatusID          TINYINT NOT NULL CONSTRAINT FK_PERSON_MARITAL   REFERENCES MARITAL_STATUS (MaritalStatusID),
    EducationID              TINYINT NOT NULL CONSTRAINT FK_PERSON_EDUCATION REFERENCES EDUCATION (EducationID),
    EduEnrollmentID          TINYINT NOT NULL CONSTRAINT FK_PERSON_ENROLL    REFERENCES EDU_ENROLLMENT (EduEnrollmentID),
    CitizenshipID            TINYINT NOT NULL CONSTRAINT FK_PERSON_CITIZEN   REFERENCES CITIZENSHIP (CitizenshipID),
    -- COUNTRY tablosu 3 farklı rolle kullanılır; ülke bilinmiyorsa (?) NULL
    BirthCountryID           TINYINT NULL     CONSTRAINT FK_PERSON_BIRTH_CTRY  REFERENCES COUNTRY (CountryID),
    FatherBirthCountryID     TINYINT NULL     CONSTRAINT FK_PERSON_FATHER_CTRY REFERENCES COUNTRY (CountryID),
    MotherBirthCountryID     TINYINT NULL     CONSTRAINT FK_PERSON_MOTHER_CTRY REFERENCES COUNTRY (CountryID),
    VetQuestionnaireAnswerID TINYINT NOT NULL CONSTRAINT FK_PERSON_VET_ANSWER  REFERENCES ANSWER (AnswerID),
    VeteransBenefits         TINYINT NOT NULL CONSTRAINT CK_PERSON_VetBenefits CHECK (VeteransBenefits IN (0, 1, 2))
);

CREATE TABLE SURVEY_RECORD (
    RecordID       INT          NOT NULL IDENTITY(1,1) CONSTRAINT PK_SURVEY_RECORD PRIMARY KEY,
    PersonID       INT          NOT NULL CONSTRAINT UQ_SURVEY_RECORD_Person UNIQUE
                                CONSTRAINT FK_SURVEY_RECORD_PERSON REFERENCES PERSON (PersonID) ON DELETE CASCADE,
    SurveyYear     SMALLINT     NOT NULL CONSTRAINT CK_SURVEY_RECORD_Year  CHECK (SurveyYear IN (1994, 1995)),
    DataSplit      VARCHAR(5)   NOT NULL CONSTRAINT CK_SURVEY_RECORD_Split CHECK (DataSplit IN ('train', 'test')),
    InstanceWeight DECIMAL(9,2) NOT NULL CONSTRAINT CK_SURVEY_RECORD_Weight CHECK (InstanceWeight > 0),
    IncomeOver50K  BIT          NOT NULL
);

CREATE TABLE EMPLOYMENT (
    PersonID               INT     NOT NULL CONSTRAINT PK_EMPLOYMENT PRIMARY KEY
                                   CONSTRAINT FK_EMPLOYMENT_PERSON REFERENCES PERSON (PersonID) ON DELETE CASCADE,
    ClassOfWorkerID        TINYINT NOT NULL CONSTRAINT FK_EMPLOYMENT_CLASS  REFERENCES CLASS_OF_WORKER (ClassOfWorkerID),
    IndustryCode           TINYINT NOT NULL CONSTRAINT FK_EMPLOYMENT_INDUSTRY REFERENCES INDUSTRY (IndustryCode),
    OccupationCode         TINYINT NOT NULL CONSTRAINT FK_EMPLOYMENT_OCCUPATION REFERENCES OCCUPATION (OccupationCode),
    EmploymentStatusID     TINYINT NOT NULL CONSTRAINT FK_EMPLOYMENT_STATUS REFERENCES EMPLOYMENT_STATUS (EmploymentStatusID),
    UnemploymentReasonID   TINYINT NOT NULL CONSTRAINT FK_EMPLOYMENT_UNEMP  REFERENCES UNEMPLOYMENT_REASON (UnemploymentReasonID),
    LaborUnionAnswerID     TINYINT NOT NULL CONSTRAINT FK_EMPLOYMENT_UNION  REFERENCES ANSWER (AnswerID),
    WeeksWorkedInYear      TINYINT NOT NULL CONSTRAINT CK_EMPLOYMENT_Weeks  CHECK (WeeksWorkedInYear BETWEEN 0 AND 52),
    NumPersonsWorkedForEmp TINYINT NOT NULL CONSTRAINT CK_EMPLOYMENT_NumPersons CHECK (NumPersonsWorkedForEmp BETWEEN 0 AND 6),
    OwnBusinessSelfEmployed TINYINT NOT NULL CONSTRAINT CK_EMPLOYMENT_OwnBusiness CHECK (OwnBusinessSelfEmployed IN (0, 1, 2))
);

-- Para değerleri tam sayı dolardır; WagePerHour cent cinsindendir (9999 = 99,99 $/saat)
CREATE TABLE FINANCE (
    PersonID            INT     NOT NULL CONSTRAINT PK_FINANCE PRIMARY KEY
                                CONSTRAINT FK_FINANCE_PERSON REFERENCES PERSON (PersonID) ON DELETE CASCADE,
    TaxFilerStatusID    TINYINT NOT NULL CONSTRAINT FK_FINANCE_TAX REFERENCES TAX_FILER_STATUS (TaxFilerStatusID),
    WagePerHour         INT     NOT NULL CONSTRAINT DF_FINANCE_Wage      DEFAULT 0
                                CONSTRAINT CK_FINANCE_Wage      CHECK (WagePerHour >= 0),
    CapitalGains        INT     NOT NULL CONSTRAINT DF_FINANCE_Gains     DEFAULT 0
                                CONSTRAINT CK_FINANCE_Gains     CHECK (CapitalGains >= 0),
    CapitalLosses       INT     NOT NULL CONSTRAINT DF_FINANCE_Losses    DEFAULT 0
                                CONSTRAINT CK_FINANCE_Losses    CHECK (CapitalLosses >= 0),
    DividendsFromStocks INT     NOT NULL CONSTRAINT DF_FINANCE_Dividends DEFAULT 0
                                CONSTRAINT CK_FINANCE_Dividends CHECK (DividendsFromStocks >= 0)
);

CREATE TABLE HOUSEHOLD (
    PersonID           INT     NOT NULL CONSTRAINT PK_HOUSEHOLD PRIMARY KEY
                               CONSTRAINT FK_HOUSEHOLD_PERSON REFERENCES PERSON (PersonID) ON DELETE CASCADE,
    HouseholdDetailID  TINYINT NOT NULL CONSTRAINT FK_HOUSEHOLD_DETAIL  REFERENCES HOUSEHOLD_DETAIL (HouseholdDetailID),
    HouseholdSummaryID TINYINT NOT NULL CONSTRAINT FK_HOUSEHOLD_SUMMARY REFERENCES HOUSEHOLD_SUMMARY (HouseholdSummaryID),
    FamilyUnder18ID    TINYINT NOT NULL CONSTRAINT FK_HOUSEHOLD_FAMILY  REFERENCES FAMILY_UNDER_18 (FamilyUnder18ID)
);

CREATE TABLE RESIDENCE (
    PersonID             INT     NOT NULL CONSTRAINT PK_RESIDENCE PRIMARY KEY
                                 CONSTRAINT FK_RESIDENCE_PERSON REFERENCES PERSON (PersonID) ON DELETE CASCADE,
    LivedInHouseAnswerID TINYINT NOT NULL CONSTRAINT FK_RESIDENCE_LIVED  REFERENCES ANSWER (AnswerID),
    PrevRegionID         TINYINT NOT NULL CONSTRAINT FK_RESIDENCE_REGION REFERENCES REGION (RegionID),
    PrevStateID          TINYINT NULL     CONSTRAINT FK_RESIDENCE_STATE  REFERENCES STATE (StateID)
);

-- Yalnızca 1994 anketinde vardır (PERSON ile 1:0..1)
CREATE TABLE MIGRATION (
    PersonID           INT     NOT NULL CONSTRAINT PK_MIGRATION PRIMARY KEY
                               CONSTRAINT FK_MIGRATION_PERSON REFERENCES PERSON (PersonID) ON DELETE CASCADE,
    MsaChangeID        TINYINT NOT NULL CONSTRAINT FK_MIGRATION_MSA     REFERENCES MSA_CHANGE (MsaChangeID),
    RegionChangeID     TINYINT NOT NULL CONSTRAINT FK_MIGRATION_REGION  REFERENCES REGION_CHANGE (RegionChangeID),
    SunbeltAnswerID    TINYINT NOT NULL CONSTRAINT FK_MIGRATION_SUNBELT REFERENCES ANSWER (AnswerID),
    WithinRegionMoveID TINYINT NOT NULL CONSTRAINT FK_MIGRATION_MOVE    REFERENCES WITHIN_REGION_MOVE (WithinRegionMoveID)
);
GO

/* ---------------------------------------------------------------------------
   C) ML (TAHMİN YÖNETİMİ) TABLOLARI - 3 adet
   --------------------------------------------------------------------------- */

CREATE TABLE ML_MODEL (
    ModelID         INT           NOT NULL IDENTITY(1,1) CONSTRAINT PK_ML_MODEL PRIMARY KEY,
    ModelName       NVARCHAR(100) NOT NULL CONSTRAINT UQ_ML_MODEL_Name UNIQUE,
    Algorithm       NVARCHAR(50)  NOT NULL,
    Hyperparameters NVARCHAR(MAX) NULL,      -- JSON metni
    TrainedAt       DATETIME2(0)  NOT NULL CONSTRAINT DF_ML_MODEL_TrainedAt DEFAULT SYSDATETIME()
);

CREATE TABLE MODEL_METRIC (
    MetricID    INT          NOT NULL IDENTITY(1,1) CONSTRAINT PK_MODEL_METRIC PRIMARY KEY,
    ModelID     INT          NOT NULL CONSTRAINT FK_MODEL_METRIC_MODEL REFERENCES ML_MODEL (ModelID) ON DELETE CASCADE,
    DataSplit   VARCHAR(5)   NOT NULL CONSTRAINT CK_MODEL_METRIC_Split CHECK (DataSplit IN ('train', 'test')),
    MetricName  VARCHAR(20)  NOT NULL,
    MetricValue DECIMAL(6,4) NOT NULL,
    CONSTRAINT UQ_MODEL_METRIC UNIQUE (ModelID, DataSplit, MetricName)
);

CREATE TABLE PREDICTION (
    PredictionID         BIGINT       NOT NULL IDENTITY(1,1) CONSTRAINT PK_PREDICTION PRIMARY KEY,
    ModelID              INT          NOT NULL CONSTRAINT FK_PREDICTION_MODEL  REFERENCES ML_MODEL (ModelID) ON DELETE CASCADE,
    RecordID             INT          NOT NULL CONSTRAINT FK_PREDICTION_RECORD REFERENCES SURVEY_RECORD (RecordID),
    PredictedProbability DECIMAL(5,4) NOT NULL CONSTRAINT CK_PREDICTION_Prob CHECK (PredictedProbability BETWEEN 0 AND 1),
    PredictedLabel       BIT          NOT NULL,
    PredictedAt          DATETIME2(0) NOT NULL CONSTRAINT DF_PREDICTION_At DEFAULT SYSDATETIME(),
    CONSTRAINT UQ_PREDICTION_Model_Record UNIQUE (ModelID, RecordID)   -- bir model bir kaydı bir kez tahmin eder
);
GO

